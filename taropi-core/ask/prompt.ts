// renderAskMessage 把一次性查证要求和原样问题合成一条用户消息。
export function renderAskMessage(question: string): string {
	return [
		"请先查证，再回答下面的问题。回答按“总览 + 逐环拆解”组织：",
		"1. 总览：先给出核心结论与整体结构 / 主链路，概括关键模块或步骤及衔接关系。",
		"2. 分步拆解（按步骤或模块循环展开，每一步都成套给出）：",
		"   - 步骤说明：该环节的职责、输入输出、关键状态或分支变化。",
		"   - 详细例子：结合真实场景、调用过程或具体数据把这一步讲透。",
		"   - 相关证据：紧跟本步附上可核对的文件路径与行号、命令输出，或可打开的链接。",
		"3. 核对说明：能用工具时先读仓库、跑只读命令，或使用已有搜索和抓取能力；未能核对的部分必须明确写出，不得把推测写成事实。仍遵守当前权限和所处阶段限制。",
		"",
		"问题：",
		question.trim(),
	].join("\n");
}
